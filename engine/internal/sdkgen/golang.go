// goPrelude is the hand-written part of the Go client: the transport, the
// options, the error and the conditional-write plumbing every method uses.
const goPrelude = `// Code generated by engine/internal/sdkgen from docs/admin-openapi.json. DO NOT EDIT.

// Package signariadmin is a client of the Signari Admin API: one method for
// each operation the server's router registers, made from the OpenAPI
// document it draws. Each method answers the decoded body and the
// configuration version the server reported, its ETag; send that version
// back with IfMatch, and a write over a deployment that moved since is
// refused with 412 rather than overwriting the other change.
package signariadmin

import (
	"bytes"
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"net/http"
	"net/url"
	"strconv"
	"strings"
	"time"
)

// Client talks to one Admin API.
type Client struct {
	// Endpoint is the base URL, such as https://admin.internal.example.com.
	Endpoint string
	// Token is an admin token, from ` + "`signari admin-token create`" + `.
	Token string
	// HTTP is the transport; nil is one with a thirty-second timeout.
	HTTP *http.Client
}

// Option changes one call.
type Option func(*callConfig)

type callConfig struct {
	ifMatch int64
	query   url.Values
}

// IfMatch makes a write conditional on the configuration version it names,
// as a read answered it.
func IfMatch(version int64) Option { return func(c *callConfig) { c.ifMatch = version } }

// Query adds a query parameter: a list's filters, limit and cursor.
func Query(key, value string) Option {
	return func(c *callConfig) {
		if c.query == nil {
			c.query = url.Values{}
		}
		c.query.Add(key, value)
	}
}

// Ptr is a pointer to v, for a request's optional fields.
func Ptr[T any](v T) *T { return &v }

// Error is a refusal, with the server's own reason.
type Error struct {
	Status int
	// Code is the server's error, such as precondition_failed.
	Code   string
	Detail string
	// ExpectedVersion and CurrentVersion are set on a 412: the version sent,
	// and the one the deployment is at.
	ExpectedVersion int64
	CurrentVersion  int64
}

func (e *Error) Error() string {
	if e.Detail != "" {
		return fmt.Sprintf("signari admin API: %s (%d): %s", e.Code, e.Status, e.Detail)
	}
	return fmt.Sprintf("signari admin API: %s (%d)", e.Code, e.Status)
}

// IsConflict reports a refused precondition: the deployment moved since the
// version was read. Read again, and decide again.
func IsConflict(err error) bool {
	var e *Error
	return errors.As(err, &e) && e.Status == http.StatusPreconditionFailed
}

// IsNotFound reports a 404.
func IsNotFound(err error) bool {
	var e *Error
	return errors.As(err, &e) && e.Status == http.StatusNotFound
}

// retries is how often a request turned away at the arrival limit is sent
// again. The limit answers 429 before the request is authenticated, so
// nothing was done and any request is safe to send again.
const retries = 8

func (c *Client) call(ctx context.Context, method, path string, body, out any, opts []Option) (int64, error) {
	var cfg callConfig
	for _, o := range opts {
		o(&cfg)
	}
	target := strings.TrimSuffix(c.Endpoint, "/") + path
	if len(cfg.query) > 0 {
		target += "?" + cfg.query.Encode()
	}
	var blob []byte
	if body != nil {
		var err error
		if blob, err = json.Marshal(body); err != nil {
			return 0, fmt.Errorf("signari admin API: encoding the request: %w", err)
		}
	}
	hc := c.HTTP
	if hc == nil {
		hc = &http.Client{Timeout: 30 * time.Second}
	}
	for attempt := 0; ; attempt++ {
		var rdr io.Reader
		if body != nil {
			rdr = bytes.NewReader(blob)
		}
		req, err := http.NewRequestWithContext(ctx, method, target, rdr)
		if err != nil {
			return 0, err
		}
		req.Header.Set("Authorization", "Bearer "+c.Token)
		req.Header.Set("Accept", "application/json")
		if body != nil {
			req.Header.Set("Content-Type", "application/json")
		}
		if cfg.ifMatch > 0 {
			req.Header.Set("If-Match", strconv.Quote(strconv.FormatInt(cfg.ifMatch, 10)))
		}
		resp, err := hc.Do(req)
		if err != nil {
			return 0, err
		}
		raw, err := io.ReadAll(io.LimitReader(resp.Body, 16<<20))
		_ = resp.Body.Close()
		if err != nil {
			return 0, err
		}
		if resp.StatusCode == http.StatusTooManyRequests && attempt < retries {
			wait, _ := strconv.Atoi(resp.Header.Get("Retry-After"))
			select {
			case <-ctx.Done():
				return 0, ctx.Err()
			case <-time.After(time.Duration(min(max(wait, 1), 30)) * time.Second):
			}
			continue
		}
		version := etag(resp.Header.Get("ETag"))
		if resp.StatusCode >= 400 {
			var e struct {
				Error    string ` + "`json:\"error\"`" + `
				Detail   string ` + "`json:\"detail\"`" + `
				Expected int64  ` + "`json:\"expected_version\"`" + `
				Current  int64  ` + "`json:\"current_version\"`" + `
			}
			_ = json.Unmarshal(raw, &e)
			if e.Error == "" {
				e.Error = http.StatusText(resp.StatusCode)
			}
			return version, &Error{Status: resp.StatusCode, Code: e.Error, Detail: e.Detail,
				ExpectedVersion: e.Expected, CurrentVersion: e.Current}
		}
		if out != nil && len(raw) > 0 {
			if err := json.Unmarshal(raw, out); err != nil {
				return version, fmt.Errorf("signari admin API: decoding %s %s: %w", method, path, err)
			}
		}
		return version, nil
	}
}

// etag reads the version out of a strong entity tag; 0 for none.
func etag(tag string) int64 {
	tag = strings.TrimPrefix(strings.TrimSpace(tag), "W/")
	v, err := strconv.ParseInt(strings.Trim(tag, "\""), 10, 64)
	if err != nil {
		return 0
	}
	return v
}
`

// goType renders a type; ptr says to make it a pointer.
func goType(t typeRef, ptr bool) string {
	var s string
	switch t.kind {
	case kString:
		s = "string"
	case kInt:
		s = "int64"
	case kFloat:
		s = "float64"
	case kBool:
		s = "bool"
	case kArray:
		s = "[]" + goType(*t.elem, false)
	case kMap:
		s = "map[string]any"
	case kNamed:
		s = t.name
	default:
		return "json.RawMessage"
	}
	if ptr || (t.nullable && t.kind != kArray && t.kind != kMap) {
		return "*" + s
	}
	return s
}

// Go makes the Go client from the OpenAPI document.
func Go(raw []byte) ([]byte, error) {
	doc, ops, err := operations(raw)
	if err != nil {
		return nil, err
	}
	m := newModel()
	requests := map[string]bool{}
	defineComponents(m, doc)
	var methods strings.Builder
	for _, op := range ops {
		name := pascal(op.ID)
		reqType, resType := "", "json.RawMessage"
		if s := op.RequestBody.schema(); s != nil {
			t := m.resolve(s, name+"Request")
			m.markRequest(t, requests)
			reqType = goType(t, false)
		}
		if s := op.success(); s != nil {
			resType = goType(m.resolve(s, name+"Response"), false)
		}
		methods.WriteString(comment("// ", name+" is "+op.method+" "+op.path+": "+op.Summary+" "+op.scopes(), 100))
		args := []string{"ctx context.Context"}
		for _, p := range op.pathParams() {
			args = append(args, camel(p)+" string")
		}
		body := "nil"
		if reqType != "" {
			args = append(args, "body "+reqType)
			body = "body"
		}
		args = append(args, "opts ...Option")
		fmt.Fprintf(&methods, "func (c *Client) %s(%s) (*%s, int64, error) {\n", name, strings.Join(args, ", "),
			resType)
		fmt.Fprintf(&methods, "\tvar out %s\n\tv, err := c.call(ctx, %q, %s, %s, &out, opts)\n", resType, op.method,
			goPath(op.path), body)
		methods.WriteString("\tif err != nil {\n\t\treturn nil, v, err\n\t}\n\treturn &out, v, nil\n}\n\n")
	}

	var b strings.Builder
	b.WriteString(goPrelude)
	b.WriteString("\n")
	for _, name := range m.order {
		def := m.structs[name]
		fmt.Fprintf(&b, "// %s is a JSON object of the Admin API.\ntype %s struct {\n", name, name)
		request := requests[name]
		for _, f := range def.fields {
			tag := f.json
			if request || !f.required {
				tag += ",omitempty"
			}
			fmt.Fprintf(&b, "\t%s %s `json:%q`\n", pascal(f.json), goType(f.t, request), tag)
		}
		b.WriteString("}\n\n")
	}
	b.WriteString(methods.String())
	out, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("sdkgen: the Go client does not format: %w", err)
	}
	return out, nil
}

// defineComponents names the document's shared schemas, but for Error: a
// refusal is the client's own Error, read from the same body.
func defineComponents(m *model, doc *document) {
	for _, name := range sortedNames(doc.Components.Schemas) {
		if name != "Error" {
			m.define(pascal(name), doc.Components.Schemas[name])
		}
	}
}

func sortedNames(m map[string]*schema) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

// markRequest marks a request's struct and every struct inside it, whose
// fields are all optional, as a request's are.
func (m *model) markRequest(t typeRef, requests map[string]bool) {
	switch t.kind {
	case kArray:
		m.markRequest(*t.elem, requests)
	case kNamed:
		def, ok := m.structs[t.name]
		if !ok || requests[t.name] {
			return
		}
		requests[t.name] = true
		for _, f := range def.fields {
			m.markRequest(f.t, requests)
		}
	}
}

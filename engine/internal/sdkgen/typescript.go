package sdkgen

import (
	"fmt"
	"strings"
)

// tsPrelude is the hand-written part of the TypeScript client. Only syntax a
// type-stripping runtime erases is used -- interfaces, type aliases, a class
// with no parameter properties -- so Node runs the module as it is.
const tsPrelude = `// Code generated by engine/internal/sdkgen from docs/admin-openapi.json. DO NOT EDIT.
//
// A client of the Signari Admin API: one method for each operation the
// server's router registers, made from the OpenAPI document it draws. Each
// method answers the decoded body and the configuration version the server
// reported, its ETag; send that version back as ifMatch, and a write over a
// deployment that moved since is refused with 412 rather than overwriting the
// other change.

/** Options for one call. */
export interface CallOptions {
  /** Makes a write conditional on the configuration version a read answered. */
  ifMatch?: number
  /** Query parameters: a list's filters, limit and cursor. */
  query?: Record<string, string>
  /** Cancels the call. */
  signal?: AbortSignal
}

/** What a call answers. */
export interface Answer<T> {
  body: T
  /** The configuration version the server reported, 0 for none. */
  version: number
}

/** A refusal, with the server's own reason. */
export class SignariAdminError extends Error {
  status: number
  code: string
  detail: string
  /** On a 412: the version sent, and the one the deployment is at. */
  expectedVersion: number
  currentVersion: number

  constructor(status: number, code: string, detail: string, expectedVersion: number, currentVersion: number) {
    super(detail ? ` + "`signari admin API: ${code} (${status}): ${detail}`" + ` : ` + "`signari admin API: ${code} (${status})`" + `)
    this.name = "SignariAdminError"
    this.status = status
    this.code = code
    this.detail = detail
    this.expectedVersion = expectedVersion
    this.currentVersion = currentVersion
  }

  /** A refused precondition: read again, and decide again. */
  get isConflict(): boolean {
    return this.status === 412
  }
}

/**
 * How often a request turned away at the arrival limit is sent again. The
 * limit answers 429 before the request is authenticated, so nothing was done.
 */
const retries = 8

function etag(tag: string | null): number {
  if (!tag) return 0
  const v = Number.parseInt(tag.replace(/^W\//, "").replaceAll('"', ""), 10)
  return Number.isFinite(v) ? v : 0
}

/** A client of one Admin API. */
export class SignariAdmin {
  endpoint: string
  token: string
  fetch: typeof globalThis.fetch

  constructor(endpoint: string, token: string, fetchImpl: typeof globalThis.fetch = globalThis.fetch) {
    this.endpoint = endpoint.replace(/\/+$/, "")
    this.token = token
    this.fetch = fetchImpl
  }

  async call<T>(method: string, path: string, body: unknown, opts: CallOptions = {}): Promise<Answer<T>> {
    let target = this.endpoint + path
    if (opts.query && Object.keys(opts.query).length > 0) {
      target += "?" + new URLSearchParams(opts.query).toString()
    }
    const headers: Record<string, string> = { Authorization: "Bearer " + this.token, Accept: "application/json" }
    if (body !== undefined) headers["Content-Type"] = "application/json"
    if (opts.ifMatch && opts.ifMatch > 0) headers["If-Match"] = '"' + opts.ifMatch + '"'
    for (let attempt = 0; ; attempt++) {
      const resp = await this.fetch(target, {
        method, headers, signal: opts.signal,
        body: body === undefined ? undefined : JSON.stringify(body),
      })
      if (resp.status === 429 && attempt < retries) {
        const wait = Math.min(Math.max(Number.parseInt(resp.headers.get("Retry-After") ?? "1", 10) || 1, 1), 30)
        await new Promise((resolve) => setTimeout(resolve, wait * 1000))
        continue
      }
      const version = etag(resp.headers.get("ETag"))
      const text = await resp.text()
      const parsed = text ? JSON.parse(text) : undefined
      if (resp.status >= 400) {
        const e = (parsed ?? {}) as Record<string, unknown>
        throw new SignariAdminError(resp.status, String(e.error ?? resp.statusText), String(e.detail ?? ""),
          Number(e.expected_version ?? 0), Number(e.current_version ?? 0))
      }
      return { body: parsed as T, version }
    }
  }
`

func tsType(t typeRef) string {
	var s string
	switch t.kind {
	case kString:
		s = "string"
	case kInt, kFloat:
		s = "number"
	case kBool:
		s = "boolean"
	case kArray:
		inner := tsType(*t.elem)
		if strings.Contains(inner, "|") {
			inner = "(" + inner + ")"
		}
		s = inner + "[]"
	case kMap:
		s = "Record<string, unknown>"
	case kNamed:
		s = t.name
	default:
		s = "unknown"
	}
	if t.nullable {
		s += " | null"
	}
	return s
}

// TypeScript makes the TypeScript client from the OpenAPI document.
func TypeScript(raw []byte) ([]byte, error) {
	doc, ops, err := operations(raw)
	if err != nil {
		return nil, err
	}
	m := newModel()
	requests := map[string]bool{}
	defineComponents(m, doc)
	var methods strings.Builder
	for _, op := range ops {
		name := pascal(op.ID)
		method := strings.ToLower(name[:1]) + name[1:]
		reqType, resType := "", "unknown"
		if s := op.RequestBody.schema(); s != nil {
			t := m.resolve(s, name+"Request")
			m.markRequest(t, requests)
			reqType = tsType(t)
		}
		if s := op.success(); s != nil {
			resType = tsType(m.resolve(s, name+"Response"))
		}
		methods.WriteString(comment("  // ", op.method+" "+op.path+": "+op.Summary+" "+op.scopes(), 100))
		var args []string
		for _, p := range op.pathParams() {
			args = append(args, camel(p)+": string")
		}
		body := "undefined"
		if reqType != "" {
			args = append(args, "body: "+reqType)
			body = "body"
		}
		args = append(args, "opts: CallOptions = {}")
		fmt.Fprintf(&methods, "  %s(%s): Promise<Answer<%s>> {\n    return this.call<%s>(%q, %s, %s, opts)\n  }\n\n",
			method, strings.Join(args, ", "), resType, resType, op.method, tsPath(op.path), body)
	}

	var b strings.Builder
	b.WriteString(tsPrelude)
	b.WriteString("\n")
	b.WriteString(strings.TrimRight(methods.String(), "\n") + "\n}\n\n")
	for _, name := range m.order {
		def := m.structs[name]
		fmt.Fprintf(&b, "/** A JSON object of the Admin API. */\nexport interface %s {\n", name)
		request := requests[name]
		for _, f := range def.fields {
			opt := ""
			if request || !f.required {
				opt = "?"
			}
			key := f.json
			if !isIdentifier(key) {
				key = fmt.Sprintf("%q", key)
			}
			fmt.Fprintf(&b, "  %s%s: %s\n", key, opt, tsType(f.t))
		}
		b.WriteString("}\n\n")
	}
	return []byte(strings.TrimRight(b.String(), "\n") + "\n"), nil
}

func isIdentifier(s string) bool {
	if s == "" {
		return false
	}
	for i, r := range s {
		if !(r == '_' || r == '$' || r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || i > 0 && r >= '0' && r <= '9') {
			return false
		}
	}
	return true
}

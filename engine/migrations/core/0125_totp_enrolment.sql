-- 0125_totp_enrolment.sql
--
-- A TOTP enrolment in progress lives apart from the credential it may replace.
--
-- # The defect
--
-- Opening /account/mfa/totp generated a secret and wrote it straight into
-- core.totp_credentials with confirmed_at = NULL. That was meant to keep an
-- unscanned authenticator from locking anyone out, and it did. But it did so by
-- OVERWRITING the user's confirmed credential, on a GET, and the session cookie
-- is SameSite=Lax -- sent on any top-level navigation from another site. So a
-- link on any page, followed by a signed-in user whose only second factor was
-- TOTP, turned their second factor off: HasSecondFactor counts only confirmed
-- credentials, and the replacement was not one. No CSRF token, no
-- re-authentication, no notice.
--
-- # The fix
--
-- The new secret is generated by a POST that carries a CSRF token, and stored
-- here. The confirmed credential is untouched until the user proves their app
-- holds the new secret; only then does the confirmation replace it, in one
-- transaction. An abandoned enrolment leaves the old factor exactly as it was.
--
-- Sealed under the subject's own key with the same context as the credential,
-- so erasure destroys a pending secret by the mechanism that destroys a live
-- one, and the confirmation can move the ciphertext without unsealing it.

SET search_path = core, public;

CREATE TABLE core.totp_enrolments (
    user_id      uuid        PRIMARY KEY REFERENCES core.users(id) ON DELETE CASCADE,
    org_id       uuid        NOT NULL REFERENCES core.organizations(id) ON DELETE RESTRICT,
    -- Sealed with the subject DEK, never stored in plaintext.
    secret_enc   bytea       NOT NULL,
    digits       smallint    NOT NULL DEFAULT 6,
    period_secs  smallint    NOT NULL DEFAULT 30,
    -- An enrolment nobody finishes is refused at confirmation after this long,
    -- rather than living as a second, half-forgotten secret.
    created_at   timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE core.totp_enrolments IS
    'A TOTP secret shown for enrolment and not yet confirmed. The confirmed credential in totp_credentials is replaced only when the user proves their app holds this one.';

ALTER TABLE core.totp_enrolments ENABLE ROW LEVEL SECURITY;
ALTER TABLE core.totp_enrolments FORCE ROW LEVEL SECURITY;
CREATE POLICY totp_enrolments_org_isolation ON core.totp_enrolments
    USING (core.is_engine() OR org_id = core.current_org_id())
    WITH CHECK (core.is_engine() OR org_id = core.current_org_id());
